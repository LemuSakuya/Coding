# 导入PyTorch库
import torch

def linear(X, w, b):
    """
    人工神经元核心线性计算（加权求和+偏置），对应神经元信号处理的第一步
    参数说明：
        X: 张量，形状[样本数, 输入特征数]，对应神经元接收的输入信号集合
        w: 张量，形状[输入特征数, 输出特征数]，对应神经元各输入信号的连接权重
        b: 张量，形状[输出特征数]，对应神经元的偏置项（调整激活阈值）
    返回值：
        y: 张量，形状[样本数, 输出特征数]，对应神经元线性加权求和后的净输出
    """
    ########## Begin ##########
    # 1. torch.mm(X, w)：输入信号与权重进行矩阵乘法，实现神经元的"加权求和"核心逻辑
    # 2. + b：对加权求和结果添加偏置项，调整神经元激活门槛，完成线性变换
    y = torch.mm(X, w) + b
    ########## End ##########
    # 返回神经元线性计算结果
    return y
